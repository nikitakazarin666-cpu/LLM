"""Чат-интерфейс симулятора кофейни с ИИ-Ментором."""

import gradio as gr
from env import BusinessSimulator
from mentor import get_mentor_advice

# Создаём симулятор
sim = BusinessSimulator(scenario_file="scenario_coffee_shop.json", seed=42)

# Системный промпт для Ментора-ведущего
SYSTEM_PROMPT = """Ты — опытный бизнес-ментор, который ведёт человека через открытие кофейни в Москве. Ты — не просто справочник, ты — живой наставник.

ТВОЯ РОЛЬ:
- Ты ведёшь игрока через все этапы: от идеи до прибыльного бизнеса.
- Ты приветствуешь его, спрашиваешь имя, узнаёшь о его опыте.
- Ты объясняешь каждый шаг простым языком.
- Ты хвалишь за правильные решения и предупреждаешь о рисках.
- Ты помнишь контекст всей беседы.

ТЕКУЩАЯ СИТУАЦИЯ:
- Игрок хочет открыть кофейню в Москве.
- У него есть бюджет, который он выберет позже.
- Сейчас он находится на этапе приветствия.

ФОРМАТ ОТВЕТА:
- Пиши тепло, но по делу.
- Используй эмодзи для оживления диалога ☕🚀
- Задавай вопросы, чтобы вовлекать игрока.
- Предлагай конкретные варианты действий."""

def chat(message, history):
    """Обрабатывает сообщение пользователя и возвращает ответ Ментора."""
    
    # Если это первое сообщение — приветствие
    if not history:
        welcome = """🧙‍♂️ **Ментор:** Приветствую, будущий предприниматель! ☕

Я вижу, ты решился на важный шаг — открыть свою кофейню. Это смелое решение, и я здесь, чтобы провести тебя через весь путь: от идеи до прибыльного бизнеса.

Но прежде чем мы начнём, скажи: как тебя зовут? И расскажи немного о себе — есть ли у тебя опыт в бизнесе или общепите?"""
        history.append({"role": "assistant", "content": welcome})
        return history
    
    # Получаем последнее сообщение пользователя
    user_message = message
    
    # Определяем этап диалога и формируем ответ
    if len(history) <= 2:
        # Этап знакомства — спрашиваем про бюджет
        response = f"""Отлично, {user_message}! Рад знакомству. 😊

Теперь давай перейдём к делу. Открытие кофейни — это инвестиция. Скажи, каким бюджетом ты располагаешь?

Выбери один из вариантов:
1. 💰 **Свои накопления** — 500 000 рублей (минимум для старта)
2. 🤝 **Инвестор (я стану твоим партнёром)** — 1 500 000 рублей (в обмен на 20% прибыли)
3. 🏦 **Банковский кредит** — 3 000 000 рублей (под высокий процент)

Напиши цифру 1, 2 или 3."""
    
    elif "1" in user_message or "накопления" in user_message.lower():
        sim.reset()
        # Выбираем концепцию To Go с малым бюджетом
        sim.current_state.cash = 500000
        response = """Ты выбрал свои накопления — 500 000 рублей. Это минимальный порог для входа, но зато ты никому не должен. 💪

Теперь давай определимся с концепцией. С таким бюджетом оптимальный выбор — **Кофе с собой (To Go)**.

Это формат:
- ☕ Только навынос, без посадочных мест
- 📍 Точка в проходимом месте (метро, офисный центр)
- 💵 Аренда 15-20 тыс./мес.
- 💰 Потенциальная прибыль 80-150 тыс./мес.

Согласен на такой формат? (да/нет)"""
    
    elif "2" in user_message or "инвестор" in user_message.lower():
        sim.reset()
        sim.current_state.cash = 1500000
        response = """Ты выбрал инвестиции — 1 500 000 рублей. Я стану твоим партнёром с долей 20% от чистой прибыли. 🤝

Это открывает больше возможностей. Ты можешь рассмотреть:
1. ☕ **Кофе с собой (To Go)** — быстрый старт, окупаемость 4-8 месяцев
2. 🏠 **Мини-кофейня с посадкой** — 5-8 мест, больше вложений, но выше чек

Какой формат тебе ближе? Напиши 1 или 2."""
    
    elif "3" in user_message or "кредит" in user_message.lower():
        sim.reset()
        sim.current_state.cash = 3000000
        response = """Ты взял кредит — 3 000 000 рублей. Помни, ежемесячный платёж составит около 80 000 рублей. ⚠️

С таким бюджетом ты можешь позволить себе классическую кофейню. Но будь осторожен: кредит давит на бюджет, и каждая ошибка может стать фатальной.

Я предлагаю рассмотреть:
1. 🏠 **Классическая кофейня** — 15-25 мест, полный цикл
2. 📦 **Франшиза** — готовая модель, но роялти 3-8% от выручки

Какой путь выбираешь? Напиши 1 или 2."""
    
    else:
        # Общий ответ — используем GigaChat
        state = sim.state()
        phase = sim.get_current_phase()
        actions = sim.get_available_actions()
        
        advice = get_mentor_advice(
            state.model_dump(),
            phase['name'],
            actions
        )
        response = advice
    
    history.append({"role": "user", "content": user_message})
    history.append({"role": "assistant", "content": response})
    
    return history

# Создаём чат-интерфейс
with gr.Blocks(title="PRO Кофе: Чат с Ментором") as demo:
    gr.Markdown("# ☕ PRO Кофе: Путь к Свободе")
    gr.Markdown("Чат-симулятор открытия кофейни с ИИ-Ментором. Просто общайся, а Ментор проведёт тебя через все этапы.")
    
    chatbot = gr.Chatbot(
        label="Диалог с Ментором",
        type="messages",
        height=600
    )
    
    msg = gr.Textbox(
        label="Твоё сообщение",
        placeholder="Напиши Ментору...",
        lines=2
    )
    
    clear = gr.Button("🔄 Начать заново")
    
    msg.submit(chat, [msg, chatbot], [chatbot])
    clear.click(lambda: [], None, [chatbot])

if __name__ == "__main__":
    demo.launch(server_name="0.0.0.0", server_port=7861)
